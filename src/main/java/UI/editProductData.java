    private void loadCategories(){
        cmbEditCategory.removeAllItems();
        
        for (Category category : categoryservice.listProductsTable()) {
            cmbEditCategory.addItem(category.getNameCategory());
        }
    }
    
    private void loadProductData(Product p){
        txtEditGTIN.setText(p.getGTIN());
        txtEditGTIN.setEditable(false);
        txtEditName.setText(p.getName());
        txtEditPrice.setText(String.valueOf(p.getPrice()));
        cmbEditCategory.setSelectedItem(p.getCategory());
        txtEditStock.setText(String.valueOf(p.getStock()));
        txtEditStockMin.setText(String.valueOf(p.getStockMin()));
    }
    
    public void updateProductData(){
        try {
            Product p = new Product();
        
            p.setGTIN(txtEditGTIN.getText().trim());
            p.setName(txtEditName.getText().trim());
            p.setPrice(Double.parseDouble(txtEditPrice.getText().trim()));
            p.setStock(Integer.parseInt(txtEditStock.getText().trim()));
            p.setStockMin(Integer.parseInt(txtEditStockMin.getText().trim()));
            
            if (cmbEditCategory.getSelectedItem() == null) {
                p.setCategory("");
            } else {
                p.setCategory(cmbEditCategory.getSelectedItem().toString());
            }
        
            String result = productservice.updateProduct(p);
            JOptionPane.showMessageDialog(this, result);
            
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(null, "Price, Stock, and Minimum Stock must be numbers");
            }
        
    }
    
    public void closePanel(){
        SwingUtilities.getWindowAncestor(this).dispose();
    }

